r"""
W6 consistency automation.

Reads every fixed result JSON (both datasets) and emits:
  1. numbers.json  — every paper-relevant statistic, canonically computed once.
  2. paper_macros.tex — \newcommand macros so the manuscript NEVER hard-codes a
     number; e.g. \MaldroidLgbmStabW expands to the value. Change data -> recompile
     -> every number updates. Kills the 0.93-vs-0.741 class of error permanently.
  3. numbers_report.txt — human-readable audit of all values with per-cell N.

Usage:
    python w6_numbers.py <results_dir_with_jsons>
Expects files named like:  maldroid_M1_fixed.json, cccs_D1_API_fixed.json, ...
and the *_paired_significance.csv / *_aggregate_ci.csv produced by the pipeline.
"""
import os, sys, json, glob, re
import numpy as np, pandas as pd
from scipy.stats import friedmanchisquare


def _friedman(matrix):
    groups=[matrix[:,j] for j in range(matrix.shape[1])]
    chi2,p=friedmanchisquare(*groups); n,k=matrix.shape
    return float(chi2),float(p),float(chi2/(n*(k-1)))

def _sig(p):
    return "***" if p<1e-3 else ("**" if p<1e-2 else ("*" if p<0.05 else "ns"))


def load_dataset(results_dir, dataset, modality_tags):
    """Load the per-modality fixed JSONs for one dataset."""
    cells_by_mod={}
    for tag in modality_tags:
        f=os.path.join(results_dir, f"{dataset}_{tag}_fixed.json")
        if not os.path.exists(f):
            # try alt naming
            alt=glob.glob(os.path.join(results_dir, f"*{tag}*fixed.json"))
            f=alt[0] if alt else None
        if f and os.path.exists(f):
            cells_by_mod[tag]=json.load(open(f))["cells"]
    return cells_by_mod


def paired_matrix(cells_by_mod, model, metric):
    """(app,seed)-matched matrix across modalities for one model+metric."""
    mods=list(cells_by_mod); table={}
    for t in mods:
        for c in cells_by_mod[t]:
            if c["model"]!=model: continue
            for r in c["records"]:
                if metric in r:
                    table.setdefault((c["seed"],r["idx"]),{})[t]=r[metric]
    rows=[[v[t] for t in mods] for v in table.values() if all(t in v for t in mods)]
    return np.array(rows), mods


def compute_all(results_dir):
    DATASETS={
        "maldroid":["M1","M2","M3"],
        "cccs":["D1_API","D2_Memory","D3_NetSys"],
    }
    METRICS=["stab_adjjac","stab_rbo","stab_rho","del_median",
             "shap_lime_adjjac_disc1","shap_lime_adjjac_disc0","intr_shap_adjjac"]
    out={"datasets":{}}
    for ds,tags in DATASETS.items():
        cbm=load_dataset(results_dir,ds,tags)
        if not cbm: continue
        models=sorted({c["model"] for t in cbm for c in cbm[t]})
        dsout={"models":models,"modalities":list(cbm),
               "macro_f1":{}, "n_common":None, "paired":{}}
        # macro-F1 per (modality,model)
        for t in cbm:
            for c in cbm[t]:
                dsout["macro_f1"][f"{t}|{c['model']}"]=round(
                    float(np.mean([cc["macro_f1"] for cc in cbm[t] if cc["model"]==c["model"]])),4)
        # coverage
        any_cell=cbm[list(cbm)[0]][0]
        dsout["n_common"]=any_cell.get("n_common")
        # paired Friedman + W for each metric x model
        for model in models:
            for m in METRICS:
                M,mods=paired_matrix(cbm,model,m)
                if M.shape[0]<3 or M.shape[1]<2: continue
                chi2,p,W=_friedman(M)
                dsout["paired"][f"{model}|{m}"]=dict(
                    n_pairs=int(M.shape[0]),chi2=round(chi2,3),
                    p=float(p),kendall_w=round(W,4),sig=_sig(p))
        out["datasets"][ds]=dsout
    return out


def emit_macros(numbers, path):
    """Emit LaTeX \newcommand macros. Macro name = camelCase of dataset+model+metric+field."""
    def cam(*parts):
        s="".join(p.replace("_","").replace("|","").title() for p in parts)
        return re.sub(r"[^A-Za-z]","",s)
    lines=["% AUTO-GENERATED by w6_numbers.py — DO NOT EDIT BY HAND.",
           "% Every paper number lives here; change data -> regenerate -> recompile.",""]
    for ds,dso in numbers["datasets"].items():
        lines.append(f"% ---- {ds} ----")
        if dso.get("n_common") is not None:
            lines.append(f"\\newcommand{{\\{cam(ds,'ncommon')}}}{{{dso['n_common']}}}")
        for key,f1 in dso["macro_f1"].items():
            lines.append(f"\\newcommand{{\\{cam(ds,key,'f1')}}}{{{f1:.3f}}}")
        for key,st in dso["paired"].items():
            base=cam(ds,key)
            lines.append(f"\\newcommand{{\\{base}W}}{{{st['kendall_w']:.3f}}}")
            lines.append(f"\\newcommand{{\\{base}Sig}}{{{st['sig']}}}")
            lines.append(f"\\newcommand{{\\{base}N}}{{{st['n_pairs']}}}")
        lines.append("")
    open(path,"w").write("\n".join(lines))
    return len(lines)


def emit_report(numbers, path):
    L=["W6 NUMBER AUDIT — single source of truth","="*50,""]
    for ds,dso in numbers["datasets"].items():
        L.append(f"\n### {ds}  (models: {dso['models']}, common-N: {dso['n_common']})")
        L.append("macro-F1:")
        for k,v in dso["macro_f1"].items(): L.append(f"   {k:20} {v:.4f}")
        L.append("paired Friedman (Kendall W, p, sig, n):")
        for k,st in dso["paired"].items():
            L.append(f"   {k:32} W={st['kendall_w']:.3f} p={st['p']:.2e} {st['sig']:3} n={st['n_pairs']}")
    open(path,"w").write("\n".join(L))


if __name__=="__main__":
    rd=sys.argv[1] if len(sys.argv)>1 else "."
    nums=compute_all(rd)
    os.makedirs("w6_out",exist_ok=True)
    json.dump(nums,open("w6_out/numbers.json","w"),indent=2)
    n=emit_macros(nums,"w6_out/paper_macros.tex")
    emit_report(nums,"w6_out/numbers_report.txt")
    print(f"wrote w6_out/numbers.json, paper_macros.tex ({n} lines), numbers_report.txt")
    for ds in nums["datasets"]:
        print(f"  {ds}: {len(nums['datasets'][ds]['paired'])} paired stats, "
              f"common-N={nums['datasets'][ds]['n_common']}")
